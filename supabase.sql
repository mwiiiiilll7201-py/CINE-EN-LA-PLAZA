create table if not exists public.funciones (
  id bigint generated by default as identity primary key,
  point_name text not null,
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  movie text not null,
  start_time time not null,
  genre text not null check (genre in ('Comedia', 'Aventura')),
  created_at timestamptz not null default now()
);

alter table public.funciones enable row level security;

-- Políticas abiertas para la demostración académica desde el navegador.
-- Para una aplicación real, reemplazar por autenticación y permisos por usuario.
drop policy if exists "lectura publica funciones" on public.funciones;
create policy "lectura publica funciones" on public.funciones
for select to anon, authenticated using (true);

drop policy if exists "insercion publica funciones" on public.funciones;
create policy "insercion publica funciones" on public.funciones
for insert to anon, authenticated with check (true);

drop policy if exists "actualizacion publica funciones" on public.funciones;
create policy "actualizacion publica funciones" on public.funciones
for update to anon, authenticated using (true) with check (true);

drop policy if exists "eliminacion publica funciones" on public.funciones;
create policy "eliminacion publica funciones" on public.funciones
for delete to anon, authenticated using (true);

